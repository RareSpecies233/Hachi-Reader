/** 章节标题块（滚动模式与翻页模式共用） */
export function chapterHeading(chapter, { compact = false } = {}) {
  const num = typeof chapter.index === 'number' ? chapter.index + 1 : null;
  return h(`header.r-ch-head${compact ? '.compact' : ''}`, [
    num != null ? h('div.r-ch-kicker', `第 ${num} 章`) : null,
    h('h2.r-ch-title', chapter.title || ''),
    h('div.r-ch-rule'),
  ]);
}

/** 单段文字 */
export function textBlock(text, settings) {
  const s = transformText(text, settings);
  if (!s) return null;
  return h('p.r-p', s);
}

/** 图片块；src 必须经 ctx.imgUrl 转成代理地址 */
export function imageBlock(rawSrc, ctx, { onOpen, eager = false } = {}) {
  if (!rawSrc) return null;
  const src = /^https?:\/\//i.test(rawSrc)
    ? ctx.imgUrl(rawSrc)
    : (rawSrc.startsWith('//') ? ctx.imgUrl(`https:${rawSrc}`) : rawSrc);
  const img = h('img.r-img', {
    src,
    alt: '',
    decoding: 'async',
    loading: eager ? 'eager' : 'lazy',
    draggable: 'false',
  });
  const fig = h('figure.r-fig', [
    img,
    h('figcaption.r-fig-cap', ''),
  ]);
  // 图片加载失败时给一条可读提示，而不是留一个破图
  img.addEventListener('error', () => {
    fig.classList.add('img-fail');
    const cap = fig.querySelector('.r-fig-cap');
    if (cap) cap.textContent = '图片加载失败';
  }, { once: true });
  img.addEventListener('load', () => {
    const cap = fig.querySelector('.r-fig-cap');
    if (cap) cap.remove();
  }, { once: true });
  if (onOpen) {
    img.addEventListener('click', (e) => {
      e.stopPropagation();
      onOpen(src, img);
    });
  }
  return fig;
}

/** 把一章的 blocks 转成节点数组（text/image） */
export function blocksToNodes(blocks, settings, ctx, opts = {}) {
  const out = [];
  for (const b of blocks || []) {
    let node = null;
    if (b.type === 'text') node = textBlock(b.text, settings);
    else if (b.type === 'image') node = imageBlock(b.src, ctx, opts);
    if (node) out.push(node);
  }
  return out;
}

/** 本章完 / 全书完 卡片（两种模式共用） */
export function endCard({ chapter, hasNext, onNext, onExit, onBackShelf, title }) {
  const btns = [];
  if (hasNext && onNext) {
    btns.push(h('button.btn.primary', { onclick: onNext }, '下一章'));
  }
  if (onBackShelf) btns.push(h('button.btn', { onclick: onBackShelf }, '返回书架'));
  return h('div.r-end', [
    h('div.r-end-mark', '· · ·'),
    h('div.r-end-title', title || (hasNext ? '本章完' : '全书完')),
    h('div.r-end-sub', hasNext ? '继续阅读下一章' : '你已经读到最后了'),
    btns.length ? h('div.r-end-actions', btns) : null,
  ]);
}

function clamp(n, min, max) {
  return Math.max(min, Math.min(max, n));
}

