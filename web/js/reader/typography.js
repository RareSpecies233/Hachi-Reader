// 主题配色不再由阅读器自己维护：全部走外壳的 MD3 角色（--md-*）。
// 新模型下 <html data-theme=配色 data-mode=亮/暗> 决定角色值，
// reader-root 同步一份 data-theme / data-mode，供 reader.css 的纸纹等选择器使用。
export function effectiveTheme(settings) {
  return PALETTE_IDS.includes(settings.themePalette) ? settings.themePalette : 'warm';
}

/** 主题、背景纹理、文字色都落在 reader-root 的 CSS 变量上 */
export function applyReaderTheme(root, settings) {
  const name = effectiveTheme(settings);
  const opacity = paperOpacity(settings);
  root.dataset.theme = name;
  // 注意：reader-root 的 data-mode 已被滚动/翻页占用，这里用 data-scheme 表示亮暗
  root.dataset.scheme = resolveMode(settings);
  // 纸纹显隐完全由「纸张强度」决定：强度 0 就是无纹理
  root.dataset.bg = opacity > 0 ? 'paper' : 'none';
  root.dataset.bgDisplay = settings.bgDisplay || 'fixed';

  // 自定义背景/文字色优先；否则交给 MD3 角色，主题切换时自动重解析。
  root.style.setProperty('--r-bg', settings.bgColor || 'var(--md-surface)');
  root.style.setProperty('--r-ink', settings.textColor || 'var(--md-on-surface)');
  root.style.setProperty('--r-muted', 'color-mix(in srgb, var(--md-on-surface-variant) 80%, var(--md-surface))');
  root.style.setProperty('--r-line', 'var(--md-outline-variant)');
  root.style.setProperty('--r-accent', 'var(--md-primary)');
  root.style.setProperty('--r-paper-opacity', String(opacity));
}

/** 字体相关变量；只改变量，不重建 DOM */
export function applyTypography(root, settings) {
  const fs = clamp(Number(settings.fontSize) || 19, 12, 40);
  const lh = clamp(Number(settings.lineHeight) || 1.85, 1.15, 3);
  const ls = clamp(Number(settings.letterSpacing) || 0, -1, 6);
  const indent = clamp(Number(settings.paragraphIndent) || 0, 0, 6);

  root.style.setProperty('--r-fs', `${fs}px`);
  root.style.setProperty('--r-lh', String(lh));
  root.style.setProperty('--r-ls', `${ls}px`);
  root.style.setProperty('--r-indent', `${indent}em`);
  // 字重：系统字体往往只有 regular/bold，其余由浏览器合成，属于预期行为
  const weight = clamp(Number(settings.fontWeight) || 400, 200, 900);
  root.style.setProperty('--r-weight', String(weight));

  // system / sans：直接用外壳的 UI 无衬线栈（iOS = PingFang SC），
  // 这条栈里没有任何衬线字体，缺字时只会退到 sans-serif，不会出现
  // 「一行里宋体/黑体混排」的逐字降级。
  // serif / custom：走 --font-read（宋体栈 / 用户上传字体，由 core/fonts.js 覆盖）。
  const fam = settings.fontFamily;
  const useUi = fam === 'system' || fam === 'sans';
  root.style.setProperty('--r-font', useUi ? 'var(--font-ui)' : 'var(--font-read)');
}

/** 计算四边留白（px）；autoMargin 打开时按视口宽度给舒适留白 */
export function computeMargins(settings) {
  const vw = Math.max(320, innerWidth || 360);
  let { marginTop, marginBottom, marginLeft, marginRight } = settings;
  let top, bottom, left, right;

  if (settings.autoMargin) {
    left = right = Math.round(Math.min(46, Math.max(20, vw * 0.062)));
    top = 24;
    bottom = 26;
  } else {
    left = Math.max(0, Math.min(160, Number(marginLeft) || 0));
    right = Math.max(0, Math.min(160, Number(marginRight) || 0));
    top = Math.max(0, Math.min(160, Number(marginTop) || 0));
    bottom = Math.max(0, Math.min(160, Number(marginBottom) || 0));
  }

  // 安全区由 CSS 的 env() 一并叠加；这里只负责“阅读留白”
  return { top, bottom, left, right };
}

export function applyMargins(root, settings) {
  const m = computeMargins(settings);
  root.style.setProperty('--r-pt', `${m.top}px`);
  root.style.setProperty('--r-pb', `${m.bottom}px`);
  root.style.setProperty('--r-pl', `${m.left}px`);
  root.style.setProperty('--r-pr', `${m.right}px`);
}

// 系统深浅切换时，reader-root 也要跟着换 data-mode / 纸纹，
// 否则「跟随系统」在阅读页里会停留在旧亮暗（index.js 只管旧 theme 字段）。
if (typeof matchMedia === 'function') {
  matchMedia('(prefers-color-scheme: dark)').addEventListener('change', () => {
    const root = document.querySelector('.reader-root');
    if (root && store.settings.themeFollow) applyReaderTheme(root, store.settings);
  });
}

